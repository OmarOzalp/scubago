function spines(cx: number, cy: number, rx: number, ry: number, n: number, len: number): string {
  let d = '';
  for (let i = 0; i < n; i++) {
    const a = (i / n) * Math.PI * 2;
    const c = Math.cos(a);
    const sn = Math.sin(a);
    d += `M${(cx + c * rx).toFixed(1)},${(cy + sn * ry).toFixed(1)} L${(cx + c * (rx + len)).toFixed(1)},${(cy + sn * (ry + len)).toFixed(1)} `;
  }
  return d;
}

