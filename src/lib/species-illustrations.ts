/** One spiral plume of a Christmas tree worm: a cone of whorls, each a little scalloped edge. */
function whorlCone(ax: number, top: number, bottom: number, halfWidth: number, tiers: number): string {
  const step = (bottom - top) / tiers;
  const half = (y: number) => halfWidth * ((y - top) / (bottom - top));
  let d = `M${ax},${top}`;
  for (let i = 1; i <= tiers; i++) {
    const y0 = top + step * (i - 1);
    const y1 = top + step * i;
    d += ` C${(ax - half(y0) - 1).toFixed(1)},${(y0 + step * 0.4).toFixed(1)} ${(ax - half(y1) - 3).toFixed(1)},${(y1 - step * 0.2).toFixed(1)} ${(ax - half(y1) - 2.4).toFixed(1)},${y1.toFixed(1)}`;
    if (i < tiers) d += ` C${(ax - half(y1)).toFixed(1)},${(y1 + 0.6).toFixed(1)} ${(ax - half(y1) * 0.8).toFixed(1)},${(y1 + 0.6).toFixed(1)} ${(ax - half(y1) * 0.8).toFixed(1)},${(y1 + 0.8).toFixed(1)}`;
  }
  d += ` C${ax - halfWidth * 0.5},${bottom + 2} ${ax + halfWidth * 0.5},${bottom + 2} ${(ax + halfWidth + 2.4).toFixed(1)},${bottom}`;
  for (let i = tiers; i >= 1; i--) {
    const y1 = top + step * i;
    const y0 = top + step * (i - 1);
    if (i < tiers) d += ` C${(ax + half(y1) * 0.8).toFixed(1)},${(y1 + 0.8).toFixed(1)} ${(ax + half(y1)).toFixed(1)},${(y1 + 0.6).toFixed(1)} ${(ax + half(y1) + 2.4).toFixed(1)},${y1.toFixed(1)}`;
    d += ` C${(ax + half(y1) + 3).toFixed(1)},${(y1 - step * 0.2).toFixed(1)} ${(ax + half(y0) + 1).toFixed(1)},${(y0 + step * 0.4).toFixed(1)} ${i === 1 ? ax : (ax + half(y0) * 0.8).toFixed(1)},${(i === 1 ? top : y0 + 0.8).toFixed(1)}`;
  }
  return `${d} Z`;
}

/** The spiral lines across a whorl cone. */
function whorlLines(ax: number, top: number, bottom: number, halfWidth: number, tiers: number): string {
  const step = (bottom - top) / tiers;
  let d = '';
  for (let i = 1; i < tiers; i++) {
    const y = top + step * i;
    const h = halfWidth * ((y - top) / (bottom - top));
    d += `M${(ax - h).toFixed(1)},${(y + 1).toFixed(1)} C${(ax - h * 0.4).toFixed(1)},${(y + step * 0.5).toFixed(1)} ${(ax + h * 0.4).toFixed(1)},${(y - step * 0.2).toFixed(1)} ${(ax + h).toFixed(1)},${(y - 1).toFixed(1)} `;
  }
  return d;
}

