/**
 * One detailed drawing per animal group, in a 200×128 box, facing left (seen from the side) or
 * head up (seen from above, for rays, hammerheads and turtles). Species paint them in their own
 * colours (species-art.ts). Paths are absolute "x,y" coordinates.
 *
 * Layers, back to front: far-side fins, the body (shaded from a darker back to a paler belly, or lit
 * from the middle when seen from above), the belly, the species' pattern, marks, shade and shine
 * (all kept inside the body), the outline, near fins and their tips, fine lines, eyes.
 *
 * To see them, compose each species with `composeArt` and write the shapes out as SVG (a
 * contact sheet in a browser shows every group at plate and card sizes, painted and in pencil).
 */
import { mirror, symmetric } from '@/lib/art-path';

export const ART_BOX = { width: 200, height: 128 } as const;

export interface Illustration {
  body: string;
  back?: string[];
  /** Far-side parts in a darker body tone (default) or the accent colour (a turtle's skin). */
  backPaint?: 'fin' | 'accent';
  fins?: string[];
  /** Fins in the fin tone (default), the accent colour, or the body's own shading. */
  finPaint?: 'fin' | 'accent' | 'body';
  finOpacity?: number;
  /** The tips of fins, painted when the species has tip-coloured fins. */
  tips?: string[];
  belly?: string;
  shade?: string[];
  shine?: string[];
  /** Fins painted in the accent colour (a humpback's white flippers, a tuna's finlets). */
  accentFins?: string[];
  /** `ifAccent`: only for species that have an accent colour (a spinner dolphin's side stripe). */
  marks?: { d: string; paint: 'accent' | 'belly' | 'fin' | 'dark' | 'light' | 'ink'; opacity?: number; clip?: boolean; ifAccent?: boolean }[];
  /** Gills, mouth, lateral line: only on bigger drawings. */
  lines?: string[];
  /** Fin rays, very faint. */
  finLines?: string[];
  eyes?: { x: number; y: number; r: number; iris?: boolean | string }[];
  light: 'side' | 'top';
  /** The body's top and bottom, for side light. */
  span: [number, number];
  /** Where the back turns to belly, 0–1 down the span. */
  split?: number;
  /** Where a pattern goes: x, y, width, height. */
  box: [number, number, number, number];
  scales?: boolean;
  /** Band positions (0–1 across the box) for banded species. */
  bands?: number[];
  bandWidth?: number;
}

/** Gill slits: `n` gentle arcs starting at x, a step apart. */
function gills(x: number, top: number, bottom: number, n = 5, step = 3.4): string[] {
  return Array.from({ length: n }, (_, i) => {
    const gx = x + i * step;
    const mid = (bottom - top) * 0.3;
    return `M${gx},${top} C${gx + 1.6},${top + mid} ${gx + 1.6},${bottom - mid} ${gx},${bottom}`;
  });
}

/** Fan of fin rays from a base point out to points along an edge. */
function rays(from: [number, number], to: [number, number][]): string[] {
  return to.map(([x, y]) => `M${from[0]},${from[1]} L${x},${y}`);
}

