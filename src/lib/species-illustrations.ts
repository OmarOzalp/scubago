/** A closed curve that wiggles in and out round an ellipse: a giant clam's wavy lips. */
function wavyEllipse(cx: number, cy: number, rx: number, ry: number, waves: number, depth: number): string {
  const steps = waves * 2;
  const pts: [number, number][] = [];
  for (let i = 0; i < steps; i++) {
    const a = (i / steps) * Math.PI * 2;
    const k = i % 2 === 0 ? 1 : 1 - depth;
    pts.push([cx + Math.cos(a) * rx * k, cy + Math.sin(a) * ry * k]);
  }
  const at = (i: number) => pts[(i + steps) % steps];
  const r = (v: number) => v.toFixed(1);
  let d = `M${r(pts[0][0])},${r(pts[0][1])}`;
  for (let i = 0; i < steps; i++) {
    const [p0, p1, p2, p3] = [at(i - 1), at(i), at(i + 1), at(i + 2)];
    d += ` C${r(p1[0] + (p2[0] - p0[0]) / 6)},${r(p1[1] + (p2[1] - p0[1]) / 6)} ${r(p2[0] - (p3[0] - p1[0]) / 6)},${r(p2[1] - (p3[1] - p1[1]) / 6)} ${r(p2[0])},${r(p2[1])}`;
  }
  return `${d} Z`;
}

